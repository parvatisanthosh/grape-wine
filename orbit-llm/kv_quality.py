from orbit_exec import OPENVINO_LIBS  # noqa: E402

PROBLEMS = Path("data/raw/humaneval/HumanEval.jsonl.gz")
PROMPTS = Path("data/humaneval_prompts.jsonl")
NEEDLE_PROMPTS = Path("data/needle_prompts.jsonl")
OASST1 = Path("data/raw/oasst1/oasst1-train.parquet")
QWEN_TOKENIZER = "C:/Users/parva/qwen2.5-coder-3b-int4/tokenizer.json"
NEEDLE_LENGTHS = [1000, 2000, 3500]  # prompt tokens (Qwen tokenizer), before the chat template
NEEDLE_DEPTHS = [0.1, 0.5, 0.9]
NEEDLE_TRIALS = 8
NEEDLE_NAMES = ["amber", "cobalt", "crimson", "ivory", "jade", "onyx", "scarlet", "silver",
                "teal", "violet", "copper", "indigo"]
NEEDLE_HEADER = "Read the text below and answer the question at the end.\n\n<text>\n"
NEEDLE_QUESTION = ("\n</text>\n\nQuestion: what is the access code for the {name} archive? "
                   "Answer with the number only.")

OUT_DIR = Path("results/kv_quality")
GENERATE = Path("cpp/build/Release/orbit_generate.exe").resolve()
MODELS = {"Q3B-INT4": "C:/Users/parva/qwen2.5-coder-3b-int4", "INT4": "C:/Users/parva/tinyllama-int4"}
TASKS = {"humaneval": PROMPTS, "needle": NEEDLE_PROMPTS}


def answers_path(model, device, kv, task="humaneval"):
    suffix = "" if task == "humaneval" else f"_{task}"
    return OUT_DIR / f"{model}_{device.lower()}_{kv}{suffix}.jsonl"


def write_jsonl(path, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as out:
        for row in rows:
            out.write(json.dumps(row) + "\n")
    print(f"{len(rows)} prompts -> {path}")


def write_prompts():
    with gzip.open(PROBLEMS, "rt", encoding="utf-8") as file:
        problems = [json.loads(line) for line in file]
    write_jsonl(PROMPTS, [{"id": p["task_id"], "content": INSTRUCTION.format(prompt=p["prompt"])}
                          for p in problems])


def needle_prompt(tokenizer, replies, rng, length, depth):
    """One retrieval prompt of `length` tokens with the answer at `depth`."""
    names = rng.sample(NEEDLE_NAMES, 3)
    codes = rng.sample(range(100000, 1000000), 3)
    facts = [f"The access code for the {name} archive is {code}" for name, code in zip(names, codes)]
    question = NEEDLE_QUESTION.format(name=names[0])

    fixed = len(tokenizer.encode(NEEDLE_HEADER + question).ids)
    fixed += sum(len(tokenizer.encode(" " + fact + ". ").ids) for fact in facts)
    budget = length - fixed
    filler, used = [], 0
    while used < budget + 50:
        reply = " ".join(rng.choice(replies).split())
        filler.append(reply)
        used += len(tokenizer.encode(" " + reply).ids)
    text = tokenizer.decode(tokenizer.encode(" ".join(filler)).ids[:budget])

    sentences = text.split(". ")
    # The real fact at the chosen depth, the two decoys at random depths.
    spots = [depth, rng.uniform(0.05, 0.95), rng.uniform(0.05, 0.95)]
    for spot, fact in sorted(zip(spots, facts), key=lambda pair: -pair[0]):
        sentences.insert(max(1, round(spot * len(sentences))), fact)
    content = NEEDLE_HEADER + ". ".join(sentences) + question
    return content, str(codes[0]), [str(code) for code in codes[1:]]


def write_needle_prompts(seed=7):
    import pandas as pd
    from tokenizers import Tokenizer

    tokenizer = Tokenizer.from_file(QWEN_TOKENIZER)
    frame = pd.read_parquet(OASST1, columns=["lang", "role", "text"])
    replies = frame[(frame.lang == "en") & (frame.role == "assistant")].text.tolist()
    rng = random.Random(seed)
    rows = []
    for length in NEEDLE_LENGTHS:
        for depth in NEEDLE_DEPTHS:
            for trial in range(NEEDLE_TRIALS):
                content, answer, decoys = needle_prompt(tokenizer, replies, rng, length, depth)
                rows.append({"id": f"needle/{length}/{depth}/{trial}", "content": content,
                             "length": length, "depth": depth, "answer": answer, "decoys": decoys,
                             "prompt_tokens": len(tokenizer.encode(content).ids)})
    write_jsonl(NEEDLE_PROMPTS, rows)


def needle_outcome(answer_text, key):
    """correct, decoy (named a decoy's code) or wrong."""
    numbers = re.findall(r"\d{6}", answer_text)
    if numbers[:1] == [key["answer"]]:
        return "correct"
    if numbers[:1] and numbers[0] in key["decoys"]:
        return "decoy"
    return "wrong"


def score_needle(model, device, precisions):
    """Exact retrieval accuracy per precision and prompt length."""
    keys = {row["id"]: row for row in load_jsonl(NEEDLE_PROMPTS)}
    results = {}
    for kv in precisions:
        answers = {row["id"]: row for row in load_jsonl(answers_path(model, device, kv, "needle"))}
        outcome = {key: needle_outcome(row["answer"], keys[key]) for key, row in answers.items()}
        results[kv] = outcome
        by_length = {}
        for key, result in outcome.items():
            by_length.setdefault(keys[key]["length"], []).append(result == "correct")
        decoys = sum(result == "decoy" for result in outcome.values())
        print(f"{kv}: {sum(r == 'correct' for r in outcome.values())}/{len(outcome)} correct, "
              f"{decoys} decoy;", {n: f"{sum(v)}/{len(v)}" for n, v in sorted(by_length.items())})
    return results


def run(model, device, precisions, limit=None, max_new_tokens=512, task="humaneval"):
    from run_experiment import prevent_sleep, require_ac_power

    require_ac_power(False)
    prevent_sleep()
    prompts = TASKS[task]
    if not prompts.exists():
        write_prompts() if task == "humaneval" else write_needle_prompts()
    env = dict(os.environ)
    env["PATH"] = f"{OPENVINO_LIBS}{os.pathsep}{env['PATH']}"
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for kv in precisions:
        command = [str(GENERATE), "--model", MODELS[model], "--device", device,
                   "--kv-precision", kv, "--prompts", str(prompts.resolve()),
                   "--out", str(answers_path(model, device, kv, task).resolve()),
                   "--max-new-tokens", str(max_new_tokens)]
        if limit:
            command += ["--limit", str(limit)]
        # No --cache-dir: a GPU model-cache hit ignores the KV precision (Finding 30).
        print(" ".join(command), flush=True)
        subprocess.run(command, env=env, check=True)


def first_difference(a, b):
    for position, (x, y) in enumerate(zip(a, b)):
        if x != y:
            return position
    return None if len(a) == len(b) else min(len(a), len(b))


def compare(model, device, precisions, task="humaneval"):
    rows = {kv: {r["id"]: r for r in load_jsonl(answers_path(model, device, kv, task))}
            for kv in precisions}
    reference = precisions[-1]  # the highest precision, e.g. f16
    shared = sorted(set.intersection(*(set(r) for r in rows.values())))
    print(f"{model} on {device}: {len(shared)} prompts answered by every precision; "
          f"reference {reference}")
    summary = []
    for kv in precisions:
        same = [rows[kv][i]["answer"] == rows[reference][i]["answer"] for i in shared]
        diffs = sorted(d for d in (first_difference(rows[kv][i]["answer"], rows[reference][i]["answer"])
                                   for i in shared) if d is not None)
        tpot = sorted(rows[kv][i]["tpot_ms"] for i in shared)
        ttft = sorted(rows[kv][i]["ttft_ms"] for i in shared)
        entry = {
            "kv": kv, "prompts": len(shared), "identical_to_reference": sum(same),
            "median_first_difference_chars": diffs[len(diffs) // 2] if diffs else None,
            "mean_tokens": round(sum(rows[kv][i]["tokens"] for i in shared) / len(shared), 1)
            if shared else None,
            "median_tpot_ms": tpot[len(tpot) // 2] if tpot else None,
            "median_ttft_ms": ttft[len(ttft) // 2] if ttft else None,
        }
        summary.append(entry)
        print(json.dumps(entry))
    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("prompts")
    sub.add_parser("needle-prompts")
    for name in ("run", "compare", "score-needle"):
        p = sub.add_parser(name)
        p.add_argument("--model", default="Q3B-INT4", choices=sorted(MODELS))
        p.add_argument("--device", default="GPU")
        p.add_argument("--kv", nargs="+", default=["default", "u8", "f16"])
        if name != "score-needle":
            p.add_argument("--task", default="humaneval", choices=sorted(TASKS))
        if name == "run":
            p.add_argument("--limit", type=int, default=None)
            p.add_argument("--max-new-tokens", type=int, default=512)
    args = parser.parse_args()
    if args.command == "prompts":
        write_prompts()
    elif args.command == "needle-prompts":
        write_needle_prompts()
    elif args.command == "run":
        run(args.model, args.device, args.kv, args.limit, args.max_new_tokens, args.task)
    elif args.command == "compare":
        compare(args.model, args.device, args.kv, args.task)
    else:
        score_needle(args.model, args.device, args.kv)


if __name__ == "__main__":
    main()
