"""Task-level quality of each KV-cache precision on the laptop (Finding 30).

Answers are generated by cpp/orbit_generate (GenAI C++ API) once per KV
precision, with greedy decoding. There are two tasks.

humaneval: the same instruction and settings as the Colab reference
  (colab/run_generation.py). Answers are compared here without running any
  code: identical answers, and where they first differ. Pass rates need the
  generated code to be executed, which is done only on Colab
  (colab/quality_core.run_program, sandboxed), never on this laptop.

needle: long-context retrieval, where KV-cache error should matter most. A fact
  ("the access code for the amber archive is 482913") and two decoys with other
  names are hidden in 1,000-3,500 tokens of real text (English OpenAssistant
  replies), and the model must return the right code. Scored here exactly.

    python kv_quality.py prompts                 # data/humaneval_prompts.jsonl
    python kv_quality.py needle-prompts          # data/needle_prompts.jsonl
    python kv_quality.py run --task humaneval --device GPU --kv default u8 f16 [--limit N]
    python kv_quality.py compare --task humaneval --device GPU --kv default u8 f16
    python kv_quality.py run --task needle --device GPU --kv default u8 f16
    python kv_quality.py score-needle --device GPU --kv default u8 f16

Answers: results/kv_quality/<model>_<device>_<kv>[_needle].jsonl
"""

